package com.afrithecus.brainbox.api.report.render

import com.afrithecus.brainbox.api.report.ReportBranding
import org.apache.pdfbox.pdmodel.font.PDFont
import org.apache.pdfbox.pdmodel.graphics.image.PDImageXObject
import org.apache.pdfbox.util.Matrix
import java.awt.Color
import kotlin.math.roundToInt

/** One resolved grading level used by the legend (session snapshot, D18). */
data class GradingBand(val label: String, val minPercentage: Double)

/**
 * Page furniture ported from the approved lab templates (plan A2, L4): the dark identity
 * band, the exam strip, footer, watermark, the school crest with its BrainBox fallback,
 * the EXAM OFFICE stamp and the session-driven grading legend.
 */
object ReportFurniture {

    private const val MARGIN = 36f

    fun initials(name: String): String {
        val builder = StringBuilder()
        for (word in name.trim().split(Regex("\\s+"))) {
            if (word.isNotEmpty()) builder.append(Character.toUpperCase(word[0]))
            if (builder.length == 2) break
        }
        return builder.toString()
    }

    /** Full-bleed dark identity band. Returns its height. */
    fun band(
        canvas: ReportCanvas,
        branding: ReportBranding,
        gradeLabel: String,
        rightTop: String,
        rightBottom: String,
        bandHeight: Float,
        logo: PDImageXObject?,
    ): Float {
        val width = canvas.width
        val height = canvas.height
        canvas.fillRect(0f, height - bandHeight, width, bandHeight, ReportTheme.DARK)
        canvas.fillRect(0f, height - bandHeight, width, 2.2f, ReportTheme.GOLD2)

        val crestX = MARGIN + 16f
        val centerY = height - bandHeight / 2f
        crest(canvas, logo, branding.schoolName, crestX, centerY, 34f)

        val textX = crestX + 30f
        canvas.text(branding.schoolName, textX, height - bandHeight / 2 + 6f, canvas.theme.serifBold, 15f, ReportTheme.PAPER)
        canvas.tracked(
            "REPORT BOOK  \u00b7  " + gradeLabel.uppercase(),
            textX,
            height - bandHeight / 2 - 9f,
            canvas.theme.sansBold,
            6.1f,
            1.5f,
            ReportTheme.GOLD2,
        )

        val rightEdge = width - MARGIN - 10f
        canvas.trackedR(
            rightTop.uppercase(),
            rightEdge,
            height - bandHeight / 2 + 6f,
            canvas.theme.sansBold,
            6.2f,
            1.3f,
            ReportTheme.mix(ReportTheme.PAPER, ReportTheme.DARK, 0.25f),
        )
        canvas.textR(rightBottom, rightEdge, height - bandHeight / 2 - 9f, canvas.theme.sansBold, 9.4f, ReportTheme.PAPER)
        return bandHeight
    }

    /** School crest: uploaded logo when present, otherwise the bundled BrainBox mark. */
    fun crest(canvas: ReportCanvas, logo: PDImageXObject?, schoolName: String, cx: Float, cy: Float, size: Float) {
        canvas.fillRound(cx - size / 2, cy - size / 2, size, size, 7f, ReportTheme.PAPER)
        canvas.ring(cx, cy, size / 2, ReportTheme.mix(ReportTheme.GOLD2, ReportTheme.PAPER, 0.25f), 0.8f)
        val image = logo ?: ReportImages.brainboxMark(canvas.document)
        if (image != null) {
            val max = size - 6f
            val scale = minOf(max / image.width, max / image.height)
            val imageWidth = image.width * scale
            val imageHeight = image.height * scale
            canvas.image(image, cx - imageWidth / 2, cy - imageHeight / 2, imageWidth, imageHeight)
            return
        }
        canvas.textC(initials(schoolName), cx, cy - 4.6f, canvas.theme.serifBold, 12.5f, ReportTheme.DARK)
    }

    /** One-line title strip under the band: left title, right meta, hairline. */
    fun strip(canvas: ReportCanvas, left: String, right: String?, bandHeight: Float, stripHeight: Float) {
        val y = canvas.height - bandHeight - stripHeight
        canvas.fillRect(MARGIN, y + stripHeight - 0.9f, canvas.width - MARGIN * 2, 0.9f, ReportTheme.LINE2)
        canvas.text(left, MARGIN, y + 7f, canvas.theme.sansBold, 8.8f, ReportTheme.NAVY)
        if (!right.isNullOrBlank()) {
            canvas.textR(right, canvas.width - MARGIN, y + 7f, canvas.theme.sans, 7.4f, ReportTheme.MUTED)
        }
    }

    fun footer(canvas: ReportCanvas, left: String, page: Int, pages: Int) {
        val width = canvas.width
        canvas.line(MARGIN, 24f, width - MARGIN, 24f, ReportTheme.LINE2, 0.8f)
        canvas.text(left, MARGIN, 12.5f, canvas.theme.sans, 6.6f, ReportTheme.MUTED)
        canvas.textR(
            "Page " + page + " of " + pages + "   \u00b7   Exam Office   \u00b7   Generated by BrainBox",
            width - MARGIN,
            12.5f,
            canvas.theme.sans,
            6.4f,
            ReportTheme.MUTED,
        )
        canvas.fillRect(0f, 0f, width, 2.6f, ReportTheme.DARK)
    }

    fun watermark(canvas: ReportCanvas, branding: ReportBranding) {
        val label = branding.watermarkText?.takeIf { it.isNotBlank() } ?: branding.schoolName
        canvas.watermark(label, canvas.width / 2, canvas.height / 2 + 30f, if (canvas.width < 700) 34f else 40f)
    }

    /** Level chip used in the lists and legend. */
    fun levelCell(canvas: ReportCanvas, grade: String, cx: Float, cy: Float, width: Float, height: Float) {
        canvas.fillRound(cx - width / 2, cy - height / 2, width, height, 2.4f, ReportTheme.gradeFill(grade))
        canvas.textC(grade, cx, cy - 2.2f, canvas.theme.sansBold, 6.2f, ReportTheme.gradeInk(grade))
    }

    /** Grading legend rendered from the session's resolved bands, not a fixed list (D18). */
    fun legend(canvas: ReportCanvas, x: Float, y: Float, bands: List<GradingBand>) {
        canvas.tracked("GRADING", x, y, canvas.theme.sansBold, 5.6f, 1.3f, ReportTheme.MUTED)
        if (bands.isEmpty()) return
        val available = canvas.width - MARGIN - (x + 48f)
        var font = 6.0f
        var gap = 10f
        while (rowWidth(canvas, bands, font, gap) > available && font > 4.8f) {
            font -= 0.4f
            gap = (gap - 2f).coerceAtLeast(4f)
        }
        var cursorX = x + 48f
        bands.forEachIndexed { index, band ->
            val low = band.minPercentage.roundToInt()
            val high = if (index == 0) 100 else bands[index - 1].minPercentage.roundToInt() - 1
            val key = band.label + " " + (if (high > low) "$low-$high" else "$low+")
            levelCell(canvas, band.label, cursorX + 7.5f, y + 2.4f, 15f, 10f)
            canvas.text(key, cursorX + 20f, y, canvas.theme.sans, font, ReportTheme.MUTED)
            cursorX += 20f + canvas.textWidth(key, canvas.theme.sans, font) + gap
        }
    }

    private fun rowWidth(canvas: ReportCanvas, bands: List<GradingBand>, font: Float, gap: Float): Float {
        var total = 0f
        bands.forEachIndexed { index, band ->
            val low = band.minPercentage.roundToInt()
            val high = if (index == 0) 100 else bands[index - 1].minPercentage.roundToInt() - 1
            val key = band.label + " " + (if (high > low) "$low-$high" else "$low+")
            total += 20f + canvas.textWidth(key, canvas.theme.sans, font) + gap
        }
        return total
    }

    /** Double-ruled EXAM OFFICE stamp, rotated 90 degrees and centred on (cx, cy). */
    fun examOfficeStamp(canvas: ReportCanvas, cx: Float, cy: Float) {
        canvas.stream.saveGraphicsState()
        // local (u,v) -> page (cx - v, cy + u): a 90 degree rotation about (cx, cy)
        canvas.stream.transform(Matrix(0f, 1f, -1f, 0f, cx, cy))
        val width = 96f
        val height = 26f
        canvas.strokeRect(-width / 2, -height / 2, width, height, ReportTheme.MUTED, 0.9f)
        canvas.strokeRect(-width / 2 + 2.4f, -height / 2 + 2.4f, width - 4.8f, height - 4.8f, ReportTheme.MUTED, 0.4f)
        canvas.trackedC("EXAM OFFICE", 0f, -0.6f, canvas.theme.sansBold, 6.6f, 1.7f, ReportTheme.MUTED)
        canvas.textC("Official record", 0f, -9.4f, canvas.theme.sans, 4.9f, ReportTheme.MUTED)
        canvas.stream.restoreGraphicsState()
    }

    /** Horizontal stamp for the totals block of a filled list page (A13). */
    fun horizontalStamp(canvas: ReportCanvas, x: Float, y: Float) {
        val width = 118f
        val height = 26f
        canvas.strokeRect(x, y, width, height, ReportTheme.MUTED, 0.9f)
        canvas.strokeRect(x + 2.4f, y + 2.4f, width - 4.8f, height - 4.8f, ReportTheme.MUTED, 0.4f)
        canvas.tracked("EXAM OFFICE", x + 14f, y + 12f, canvas.theme.sansBold, 6.6f, 1.6f, ReportTheme.MUTED)
        canvas.text("Official record", x + 14f, y + 4.5f, canvas.theme.sans, 4.9f, ReportTheme.MUTED)
    }

    fun divider(canvas: ReportCanvas, y: Float, color: Color = ReportTheme.LINE) {
        canvas.line(MARGIN, y, canvas.width - MARGIN, y, color, 0.6f)
    }
}
