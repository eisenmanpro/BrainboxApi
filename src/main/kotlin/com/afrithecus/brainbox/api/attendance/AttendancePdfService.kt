package com.afrithecus.brainbox.api.attendance

import org.apache.pdfbox.pdmodel.PDDocument
import org.apache.pdfbox.pdmodel.PDPage
import org.apache.pdfbox.pdmodel.PDPageContentStream
import org.apache.pdfbox.pdmodel.common.PDRectangle
import org.apache.pdfbox.pdmodel.font.PDFont
import org.apache.pdfbox.pdmodel.font.PDType1Font
import org.apache.pdfbox.pdmodel.font.Standard14Fonts
import org.springframework.stereotype.Service
import java.awt.Color
import java.io.ByteArrayOutputStream
import java.time.LocalDate
import java.time.format.DateTimeFormatter

/** One row of the rendered attendance register. */
data class AttendancePdfRow(
    val studentName: String,
    val present: Int,
    val late: Int,
    val absent: Int,
    val excused: Int,
    val rate: Double,
)

/**
 * Renders a printable attendance register PDF (doc 04 §4.1 export-pdf) with
 * PDFBox. The school name and a brand-coloured header make the export look like
 * a school document rather than a bare table; the footer carries the generation
 * date so a printed copy is self-describing.
 */
@Service
class AttendancePdfService {

    private val brand = Color(0x58, 0x11, 0x1A)
    private val brandSoft = Color(0xF4, 0xEE, 0xEF)
    private val ink = Color(0x1F, 0x29, 0x37)
    private val muted = Color(0x64, 0x74, 0x8B)
    private val line = Color(0xD8, 0xDE, 0xE6)

    fun render(
        schoolName: String,
        className: String,
        range: String,
        rows: List<AttendancePdfRow>,
        averageAttendance: Double,
        generatedOn: LocalDate,
    ): ByteArray {
        PDDocument().use { document ->
            val font = PDType1Font(Standard14Fonts.FontName.HELVETICA)
            val bold = PDType1Font(Standard14Fonts.FontName.HELVETICA_BOLD)
            var page = newPage(document)
            var content = PDPageContentStream(document, page)
            var y = 800f

            // Brand band: school name + document title.
            content.setNonStrokingColor(brand)
            content.addRect(0f, 742f, PDRectangle.A4.width, 100f)
            content.fill()
            content.setNonStrokingColor(Color.WHITE)
            write(content, bold, 18f, 40f, 805f, schoolName.ifBlank { "Brainbox" })
            write(content, font, 11f, 40f, 786f, "Attendance Register")
            write(content, font, 9f, 40f, 770f, "Generated by Brainbox on " + generatedOn.format(DateTimeFormatter.ofPattern("d MMM yyyy")))
            y = 706f

            content.setNonStrokingColor(ink)
            write(content, bold, 14f, 40f, y, className)
            y -= 18f
            write(content, font, 10f, 40f, y, range)
            y -= 16f
            write(content, font, 10f, 40f, y, "Average attendance: " + averageAttendance + "%")
            y -= 26f

            drawHeader(content, bold, y)
            y -= 6f
            content.setNonStrokingColor(line)
            content.setLineWidth(1f)
            content.moveTo(40f, y)
            content.lineTo(555f, y)
            content.stroke()
            y -= 16f

            var stripe = false
            if (rows.isEmpty()) {
                content.setNonStrokingColor(muted)
                write(content, font, 10f, 40f, y, "No registers recorded in this range.")
            }
            for (row in rows) {
                if (y < 60f) {
                    content.close()
                    page = newPage(document)
                    content = PDPageContentStream(document, page)
                    y = 790f
                    content.setNonStrokingColor(brand)
                    content.addRect(0f, 752f, PDRectangle.A4.width, 40f)
                    content.fill()
                    content.setNonStrokingColor(Color.WHITE)
                    write(content, bold, 12f, 40f, 778f, schoolName.ifBlank { "Brainbox" } + " - Attendance (continued)")
                    y = 726f
                    content.setNonStrokingColor(ink)
                    drawHeader(content, bold, y)
                    y -= 6f
                    content.setNonStrokingColor(line)
                    content.moveTo(40f, y)
                    content.lineTo(555f, y)
                    content.stroke()
                    y -= 16f
                    stripe = false
                }
                if (stripe) {
                    content.setNonStrokingColor(brandSoft)
                    content.addRect(36f, y - 4f, 519f, 18f)
                    content.fill()
                }
                content.setNonStrokingColor(ink)
                write(content, font, 10f, 40f, y, row.studentName)
                write(content, font, 10f, 300f, y, row.present.toString())
                write(content, font, 10f, 345f, y, row.late.toString())
                write(content, font, 10f, 390f, y, row.absent.toString())
                write(content, font, 10f, 435f, y, row.excused.toString())
                write(content, bold, 10f, 485f, y, row.rate.toString() + "%")
                y -= 18f
                stripe = !stripe
            }

            // Footer on every page is drawn last so it never collides with rows.
            content.setNonStrokingColor(muted)
            write(content, font, 8f, 40f, 34f, "Attendance register - " + className + " - " + range)
            content.close()

            val out = ByteArrayOutputStream()
            document.save(out)
            return out.toByteArray()
        }
    }

    private fun drawHeader(content: PDPageContentStream, bold: PDFont, y: Float) {
        content.setNonStrokingColor(ink)
        write(content, bold, 9f, 40f, y, "STUDENT")
        write(content, bold, 9f, 300f, y, "PRESENT")
        write(content, bold, 9f, 345f, y, "LATE")
        write(content, bold, 9f, 390f, y, "ABSENT")
        write(content, bold, 9f, 435f, y, "EXCUSED")
        write(content, bold, 9f, 485f, y, "RATE")
    }

    private fun write(content: PDPageContentStream, face: PDFont, size: Float, x: Float, y: Float, value: String) {
        content.beginText()
        content.setFont(face, size)
        content.newLineAtOffset(x, y)
        content.showText(sanitize(value))
        content.endText()
    }

    private fun newPage(document: PDDocument): PDPage {
        val page = PDPage(PDRectangle.A4)
        document.addPage(page)
        return page
    }

    /** Standard-14 fonts are WinAnsi; drop anything they cannot encode. */
    private fun sanitize(value: String): String =
        value.map { if (it.code in 32..255) it else '?' }.joinToString("")
}
