// ---------------------------------------------------------------------------
// Traditional (paper) exam payloads. Field names mirror the Android models in
// models/traditional/*.kt and models/analytics/*.kt exactly (client wins over
// the prose docs where they differ).
// ---------------------------------------------------------------------------

data class SubjectComponentDto(
    val componentId: String,
    val name: String,
    val maxScore: Int,
    val weight: Double = 1.0,
)

data class SubjectConfigDto(
    val subjectId: String,
    val name: String,
    val maxScore: Int,
    val type: TraditionalSubjectType = TraditionalSubjectType.SINGLE,
    val components: List<SubjectComponentDto>? = null,
    val isOptional: Boolean = false,
)

data class TraditionalExamDto(
    val examId: String,
    val title: String,
    val term: ExamTerm,
    val gradeLevel: String,
    val year: Int,
    val type: String = "TRADITIONAL",
    val status: TraditionalExamStatus,
    val subjects: List<SubjectConfigDto>,
    val maxScore: Int = 100,
    val autoGenerated: Boolean = true,
    /** Capture-session instruction; auto-filled by the server when the creator leaves it blank. */
    val sessionRemarks: String? = null,
    /** What finalize should do with incomplete learners; default is the owner's "omit all incomplete". */
    val omitPolicy: TraditionalOmitPolicy = TraditionalOmitPolicy.OMIT_ALL_INCOMPLETE,
    /** True when the caller themself has already submitted/confirmed this exam. */
    val confirmedByMe: Boolean = false,
    /** When the caller's confirmation was recorded; null when they have not submitted (F7-A4). */
    val submittedAt: Long? = null,
    val createdAt: Long,
    val finalizedAt: Long? = null,
    val finalizedBy: String? = null,
    val coordinatorRemarks: String? = null,
    val publishedAt: Long? = null,
    val publishedBy: String? = null,
    /** Tenant scope so the client can preserve it across pulls (TE-3). */
    val schoolId: String? = null,
)

data class TraditionalMarkDto(
    val id: String,
    val examId: String,
    val studentId: String,
    val subjectId: String,
    val rawScore: Int,
    val percentage: Double? = null,
    val gradeBand: String? = null,
    val componentScores: Map<String, Int>? = null,
    val confirmedByTeacher: Boolean = false,
    val confirmedAt: Long? = null,
    val enteredAt: Long,
)

data class MarkEntryDto(
    val studentId: String,
    val subjectId: String,
    val rawScore: Int,
    val componentScores: Map<String, Int>? = null,
    /** Stable class id for the capture row (F7-A6); optional for older clients. */
    val classId: String? = null,
)

data class ExamConfirmationStatusDto(
    val examId: String,
    val totalTeachers: Int,
    val confirmedCount: Int,
    val pendingTeachers: List<String>,
    /** Display names for the same ids, so the UI never shows a raw UUID. */
    val pendingTeacherNames: List<String> = emptyList(),
)

/** One learner inside a coordinator capture-summary class. No marks are exposed here. */
data class CaptureStudentDto(
    val studentId: String,
    val name: String,
    val admissionNumber: String,
    val classTag: String,
    val status: CaptureStudentStatus,
    val recordedSubjects: Int,
    val expectedSubjects: Int,
)

enum class CaptureStudentStatus { COMPLETE, PARTIAL, NONE }

data class ClassCaptureSummaryDto(
    val classTag: String,
    val teacherName: String,
    val totalStudents: Int,
    val completeStudents: Int,
    val partialStudents: Int,
    val missingStudents: Int,
    val students: List<CaptureStudentDto>,
)

/**
 * Coordinator/class-teacher capture summary. Counts and learner identities only;
 * the brief is explicit that the review screen must not pull every learner's marks.
 */
data class CaptureSummaryDto(
    val examId: String,
    val title: String,
    val gradeLevel: String,
    val term: ExamTerm,
    val year: Int,
    val sessionRemarks: String? = null,
    val totalStudents: Int,
    val studentsWithMarks: Int,
    val studentsWithEmptyFields: Int,
    val studentsWithNoScores: Int,
    val myConfirmed: Boolean = false,
    val classes: List<ClassCaptureSummaryDto>,
)

/** One class that can be selected for capture; the teacher's own class is returned with allowed=false. */
data class TraditionalClassDto(
    val classId: String,
    val name: String,
    val gradeLevel: String,
    val teacherId: String? = null,
    val teacherName: String? = null,
    val allowed: Boolean = true,
)

/** Coordinator edit of a saved capture session (title/remarks/omit policy). */
data class UpdateTraditionalExamRequest(
    val title: String? = null,
    val remarks: String? = null,
    val omitPolicy: TraditionalOmitPolicy? = null,
)

