/**
 * Coordinator/class-teacher capture summary. Counts and learner identities only;
 * the brief is explicit that the review screen must not pull every learner's marks.
 */
data class CaptureSummaryDto(
    val examId: String,
    val title: String,
    val gradeLevel: String,
    val term: ExamTerm,
    val year: Int,
    val sessionRemarks: String? = null,
    val totalStudents: Int,
    val studentsWithMarks: Int,
    val studentsWithEmptyFields: Int,
    val studentsWithNoScores: Int,
    val myConfirmed: Boolean = false,
    /**
     * True when the server narrowed this summary to the caller's own class because they are a
     * class teacher who is not a coordinator/ICT admin: `classes`, every count below and
     * `totalStudents` then describe that one class only. Additive: clients that ignore it keep
     * working, and coordinators/admins always see the full grade (false).
     */
    val ownClassOnly: Boolean = false,
    val classes: List<ClassCaptureSummaryDto>,
)

/** One class that can be selected for capture; the teacher's own class is returned with allowed=false. */
data class TraditionalClassDto(
    val classId: String,
    val name: String,
    val gradeLevel: String,
    val teacherId: String? = null,
    val teacherName: String? = null,
    val allowed: Boolean = true,
    /** The class this caller is server-locked to for the session, if any (V33). */
    val lockedClassId: String? = null,
    /** Same lock as a class name so clients that key on classTag can restore it. */
    val lockedClassName: String? = null,
    /** Set when another teacher already bound this class for the session. */
    val lockedByTeacherId: String? = null,
    val lockedByTeacherName: String? = null,
    /** True once finalisation ignored this class; it never appears as a live capture target. */
    val archived: Boolean = false,
    /** A class in this exam already held by another teacher, and who holds it. */
    val otherClassName: String? = null,
    val otherClassTeacherName: String? = null,
)

/** One class's submission state for the coordinator's remaining-class counter. */
data class ClassSubmissionDto(
