/** Body for POST /traditional/exams (client sends the full TraditionalExam model). */
data class CreateTraditionalExamRequest(
    /** The client's deterministic exam id; stored and echoed so CREATE_EXAM replay is idempotent. */
    val examId: String? = null,
    @field:NotBlank val title: String,
    @field:NotNull val term: ExamTerm,
    @field:NotBlank val gradeLevel: String,
    @field:NotNull val year: Int,
    @field:NotEmpty val subjects: List<SubjectConfigDto>,
    val maxScore: Int = 100,
    val autoGenerated: Boolean = true,
    /** Coordinator's capture instructions; blank gets a sensible default server-side. */
    val remarks: String? = null,
    /** Android sends the same field under the response model's name. */
    val sessionRemarks: String? = null,
    val omitPolicy: TraditionalOmitPolicy = TraditionalOmitPolicy.OMIT_ALL_INCOMPLETE,
)
