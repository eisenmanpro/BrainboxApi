data class GradingBandDto(
    val grade: String,
    val minPercentage: Int,
)

data class OverallGradingBandDto(
    val grade: String,
    val minRawScore: Int,
)

data class GradingConfigDto(
    val bands: List<GradingBandDto> = GradingConfigDefaults.bands(),
    val overallBands: List<OverallGradingBandDto>? = null,
)

/** Default CBC bands shared with the client (models/traditional/TraditionalExamGrading.kt). */
object GradingConfigDefaults {
    fun bands(): List<GradingBandDto> = listOf(
        GradingBandDto("EE", 80),
        GradingBandDto("ME", 65),
        GradingBandDto("AE", 50),
        GradingBandDto("BE", 35),
        GradingBandDto("DE", 20),
        GradingBandDto("E", 0),
    )

    fun overallBands(): List<OverallGradingBandDto> = listOf(
        OverallGradingBandDto("EE", 350),
        OverallGradingBandDto("ME", 280),
        OverallGradingBandDto("AE", 200),
        OverallGradingBandDto("BE", 120),
    )
}

